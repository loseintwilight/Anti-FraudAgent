    def generate(
        self,
        fraud_type: str,
        risk_level: str,
        user_role: str = "unknown",
    ) -> Optional[str]:
        """
        生成劝导话术

        Args:
            fraud_type: 诈骗类型
            risk_level: 风险等级 (HIGH/EXTREME)
            user_role: 用户角色

        Returns:
            劝导话术文本，低风险或无匹配时返回 None
        """
        risk_level_upper = risk_level.upper()

        # 低风险不劝导
        if risk_level_upper in ("LOW", "MEDIUM"):
            logger.info(f"低风险，无需劝导: risk_level={risk_level_upper}")
            return None

        logger.info(
            f"生成劝导话术: fraud_type={fraud_type}, "
            f"risk_level={risk_level_upper}, user_role={user_role}"
        )

        # 获取诈骗类型对应的话术
        type_messages = self._PERSUASION_MAP.get(fraud_type)
        message = None

        if type_messages:
            # 尝试获取用户角色对应的话术
            message = type_messages.get(user_role)
            # 如果没有角色对应的话术，使用该类型第一条
            if not message and type_messages:
                message = list(type_messages.values())[0]

        # 如果诈骗类型无对应话术，使用默认通用劝导
        if not message:
            message = self._DEFAULT_MESSAGES.get(user_role)
            if not message:
                message = self._DEFAULT_MESSAGES.get("youth")

        # 极高风险追加紧急提示
        if risk_level_upper == "EXTREME":
            message += self._EXTREME_APPEND

        logger.info("劝导话术生成成功")
        return message

    def get_supported_types(self) -> list:
        """获取支持的诈骗类型列表"""
        return list(self._PERSUASION_MAP.keys())


