# 年龄组映射
AGE_GROUP_TEMPLATES: Dict[str, Dict[str, List[str]]] = {
    "young": YOUNG_TEMPLATES,
    "middle": MIDDLE_TEMPLATES,
    "elderly": ELDERLY_TEMPLATES,
}

# 年龄到年龄组的映射
AGE_GROUP_MAP = [
    (0, 25, "young"),
    (26, 50, "middle"),
    (51, 150, "elderly"),
]


def _resolve_age_group(age_group: str) -> str:
    """标准化年龄组名称"""
    age_group = age_group.lower().strip()
    if age_group in ("young", "youth", "学生", "younger"):
        return "young"
    if age_group in ("middle", "mid", "中年", "上班族"):
        return "middle"
    if age_group in ("elderly", "old", "老年", "elder"):
        return "elderly"
    return "middle"


class PersuasionGenerator:
    """
    劝导话术生成器
    根据诈骗类型和年龄组生成口语化劝阻话术
    """

    def generate(
        self,
        fraud_type: str,
        age_group: str = "middle",
        user_name: str = "",
    ) -> str:
        """
        生成劝导话术

        参数:
            fraud_type: 诈骗类型（应与 FraudClassifier 的输出一致）
            age_group: 年龄组 young/middle/elderly
            user_name: 用户称呼（可选）

        返回:
            劝导话术文本
        """
        logger.info(
            f"生成劝导话术: fraud_type={fraud_type}, "
            f"age_group={age_group}"
        )

        group_key = _resolve_age_group(age_group)
        templates = AGE_GROUP_TEMPLATES.get(group_key, MIDDLE_TEMPLATES)

        # 获取对应诈骗类型的话术列表
        fraud_templates = templates.get(fraud_type)

        # 如果找不到对应类型的话术，使用"可疑"模板
        if not fraud_templates:
            fraud_templates = templates.get("可疑", templates.get("未知", []))

        # 使用确定性选择（基于诈骗类型的哈希值选择一句话术）
        idx = int(hashlib.md5(fraud_type.encode()).hexdigest(), 16) % len(fraud_templates)
        text = fraud_templates[idx]

        # 如果有用户称呼，尝试插入到话术中
        if user_name:
            if len(text) > 10:
                text = f"{user_name}，{text[0].lower()}{text[1:]}"

        logger.info(f"话术生成完成: {text[:50]}...")
        return text
